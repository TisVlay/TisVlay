//! Compiles the Slint UI and emits build-time env vars / bundled-deps
//! blob. Lives at the GUI crate's root because it owns artifacts that
//! end up baked into the binary itself.

use std::path::{Path, PathBuf};
use std::process::Command;

fn main() {
    slint_build::compile("ui/main.slint").unwrap();

    // The About pane's diagnostic-copy button emits a JSON blob that
    // includes the bundled Slint version. Lift it from `Cargo.lock`
    // so it stays in sync with the resolved dep automatically — no
    // hand-edit when the workspace bumps slint.
    let version = read_dep_version_from_lock("slint")
        .expect("couldn't determine slint version from Cargo.lock");
    println!("cargo:rustc-env=TISVLAY_GUI_SLINT_VERSION={version}");

    let lock = workspace_root().join("Cargo.lock");
    println!("cargo:rerun-if-changed={}", lock.display());

    generate_third_party_licenses();
}

/// Generate `$OUT_DIR/THIRD-PARTY-LICENSES.txt` for `include_str!`
/// embedding into the About → Notices pane. Runs `cargo-about` with
/// the workspace-root config + plain-text template; on failure (most
/// commonly: `cargo-about` not on `$PATH` in a clean dev env without
/// the Nix shell) writes a stub blob with install instructions and
/// emits a `cargo:warning=` rather than failing the build.
fn generate_third_party_licenses() {
    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR not set");
    let out_path = Path::new(&out_dir).join("THIRD-PARTY-LICENSES.txt");
    let workspace = workspace_root();
    let manifest = workspace.join("Cargo.toml");
    let template = workspace.join("about.txt.hbs");

    // Re-run when the inputs change. Cargo.lock is already declared
    // above; about.toml / about.txt.hbs are template + config.
    println!(
        "cargo:rerun-if-changed={}",
        workspace.join("about.toml").display()
    );
    println!("cargo:rerun-if-changed={}", template.display());

    let output = Command::new("cargo-about")
        .arg("generate")
        .arg("--manifest-path")
        .arg(&manifest)
        .arg("--workspace")
        .arg("--all-features")
        .arg("--locked")
        .arg("--fail")
        .arg(&template)
        .output();

    let blob = match output {
        Ok(out) if out.status.success() => out.stdout,
        Ok(out) => {
            // cargo-about ran but failed (license-resolution error,
            // template syntax error, …). Surface stderr so the
            // developer can see what broke; fall through to the stub.
            let stderr = String::from_utf8_lossy(&out.stderr);
            println!(
                "cargo:warning=cargo-about generate failed (status: {}); embedding stub. stderr:",
                out.status
            );
            for line in stderr.lines() {
                println!("cargo:warning=  {line}");
            }
            stub_notices_blob().into_bytes()
        }
        Err(e) => {
            // `cargo-about` not on `$PATH`, or some other spawn
            // failure. Most common case: clean dev env without the
            // Nix shell. Don't fail the build — write a stub the
            // Notices pane will surface verbatim.
            println!(
                "cargo:warning=cargo-about not invocable ({e}); embedding stub blob in tisvlay-gui's About → Notices pane. Install with `cargo install --locked cargo-about` (or run inside the Nix dev shell) to populate."
            );
            stub_notices_blob().into_bytes()
        }
    };

    std::fs::write(&out_path, blob).expect("write THIRD-PARTY-LICENSES.txt");
}

fn stub_notices_blob() -> String {
    "Third-party license attribution was not generated for this build.\n\
     \n\
     The About → Notices pane normally embeds a workspace-wide bundle\n\
     produced by `cargo-about` at build time. To populate it:\n\
     \n\
       - Use the Nix dev shell (cargo-about is provisioned there), or\n\
       - Install manually: cargo install --locked cargo-about\n\
     \n\
     Once cargo-about is on $PATH, rebuild tisvlay-gui to regenerate\n\
     this bundle. The packaged distribution at\n\
     /usr/share/doc/tisvlay/THIRD-PARTY-LICENSES.html ships the same\n\
     attribution data, generated by `just licenses-html` before nfpm\n\
     bundles each .deb / .rpm / .pkg.tar.zst.\n"
        .to_string()
}

fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .canonicalize()
        .expect("couldn't canonicalize workspace root")
}

fn read_dep_version_from_lock(name: &str) -> Option<String> {
    let lock = std::fs::read_to_string(workspace_root().join("Cargo.lock")).ok()?;
    let value: toml::Value = toml::from_str(&lock).ok()?;
    let packages = value.get("package")?.as_array()?;
    for pkg in packages {
        if pkg.get("name")?.as_str() == Some(name) {
            return pkg.get("version")?.as_str().map(str::to_owned);
        }
    }
    None
}
